#ifndef ITEMSDATAPROVIDER_H
#define ITEMSDATAPROVIDER_H

#include <vector>
#include <string>
#include <tuple>

enum class ItemType { Analog, Discrete };
enum class RetrievalType { Resolution, RowCount, MaxVisible };

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
struct ItemDef
{
    std::string name;
    std::string description;
    std::string dataSource;
    double rangeMin;
    double rangeMax;
    ItemType type;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
struct ProviderParams
{
    std::string fullName;
    bool isResolutionEnabled;
    bool isRowcountEnabled;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
struct HistDataItemReadingParams
{
    std::string itemName;
    std::string aStart;
    std::string aEnd;
    ItemType itemType;
    RetrievalType itemRetrievalType;
    int retrievalValue;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
using DataProviderHistValueType = std::tuple<std::string, double, bool>;
using DataProviderHistValueType3D = std::tuple<std::string, double, double, bool>;
using DataProviderLiveValueType = std::pair<double, bool>;

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
class IItemsProvider
{
public:
    virtual ~IItemsProvider() {}

    virtual int getAllItems(std::vector<ItemDef>& outItems) = 0;
    virtual int getProviderParams(ProviderParams& outParams) = 0;
    std::string myDllPath;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
template<typename TypeOfValues2D3D>
class IHistDataProvider : public virtual IItemsProvider
{
public:
    virtual ~IHistDataProvider(){}

    virtual int readItemHist(HistDataItemReadingParams aItemParam, std::vector<TypeOfValues2D3D>& outHistData) = 0;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
class ILiveDataProvider : public virtual IItemsProvider
{
public:
    virtual ~ILiveDataProvider(){}

    virtual int readItemLive(std::string aItemName, ItemType aItemType, DataProviderLiveValueType& outLiveData) = 0;
};

///////////////////////////////////////////////////////////////////////////////
//
///////////////////////////////////////////////////////////////////////////////
typedef IItemsProvider* (*ProviderCreateFunctionType)(std::string dllPath);

#endif // ITEMSDATAPROVIDER_H
